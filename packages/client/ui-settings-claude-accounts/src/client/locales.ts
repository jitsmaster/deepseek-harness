/**
 * Fill the `{name}` placeholders of one translated string.
 * @param text - the translated string.
 * @param values - replacement for each placeholder name.
 * @returns the string with every known placeholder replaced.
 */
export function fill(text: string, values: Readonly<Record<string, string>>): string {
  return text.replaceAll(/\{(\w+)\}/gu, (whole, name: string) => values[name] ?? whole)
}
